import { describe, expect, it } from 'vitest';
import { SqlParser } from '../../parser/SqlParser.js';
import { buildDDL } from '../../utils/ddlGenerators.js';

describe('SQL import fidelity', () => {
  it('保留数字类型的 UNSIGNED 与零精度并可重新生成', async () => {
    const sql = `CREATE TABLE amounts (
      id BIGINT UNSIGNED PRIMARY KEY,
      amount DECIMAL(10,2) UNSIGNED,
      created_at DATETIME(0)
    );`;
    const parser = new SqlParser();
    const result = await parser.parseAsync(sql, 'mysql');

    expect(result.fields.map((field) => field.type)).toEqual([
      'BIGINT UNSIGNED',
      'DECIMAL(10,2) UNSIGNED',
      'DATETIME(0)',
    ]);

    const generated = buildDDL({ ...result, dbType: 'mysql' });
    const reparsed = await parser.parseAsync(generated, 'mysql');
    expect(reparsed.fields).toEqual(result.fields);
  });

  it('ENUM 与 SET 的值在导入和生成后保留大小写、标点、空白和转义', async () => {
    const sql = String.raw`CREATE TABLE choices (
      state ENUM('Open','a,b','Mixed) Case','not null','it''s',' padded ','path\\value'),
      flags SET('First','A,B','default value')
    );`;
    const parser = new SqlParser();
    const result = await parser.parseAsync(sql, 'mysql');

    expect(result.fields.map((field) => field.type)).toEqual([
      String.raw`ENUM('Open', 'a,b', 'Mixed) Case', 'not null', 'it''s', ' padded ', 'path\\value')`,
      "SET('First', 'A,B', 'default value')",
    ]);

    const generated = buildDDL({ ...result, dbType: 'mysql' });
    const reparsed = await parser.parseAsync(generated, 'mysql');
    expect(reparsed.fields).toEqual(result.fields);
  });

  it('保留 PostgreSQL 数组类型的维度并可重新生成', async () => {
    const sql = `CREATE TABLE arrays (
      ids INT[],
      tags VARCHAR(20)[],
      amounts NUMERIC(10,2)[],
      codes INT ARRAY,
      grid TEXT[][]
    );`;
    const parser = new SqlParser();
    const result = await parser.parseAsync(sql, 'postgresql');

    expect(result.fields.map((field) => field.type)).toEqual([
      'INT[]',
      'VARCHAR(20)[]',
      'NUMERIC(10,2)[]',
      'INT[]',
      'TEXT[][]',
    ]);

    const generated = buildDDL({ ...result, dbType: 'postgresql' });
    const reparsed = await parser.parseAsync(generated, 'postgresql');
    expect(reparsed.fields).toEqual(result.fields);
  });

  it('PostgreSQL 生成的 BY DEFAULT IDENTITY 列可重新导入并生成相同 DDL', async () => {
    const parser = new SqlParser();

    const source = await parser.parseAsync(
      'CREATE TABLE orders (id BIGINT GENERATED BY DEFAULT AS IDENTITY);',
      'postgresql',
    );

    expect(source.fields[0]).toMatchObject({ nullable: false, defaultKind: 'auto_increment' });

    const generated = buildDDL({ ...source, dbType: 'postgresql' });
    expect(generated).toContain('id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL');
    const reparsed = await parser.parseAsync(generated, 'postgresql');
    expect(reparsed.fields).toEqual(source.fields);
    expect(buildDDL({ ...reparsed, dbType: 'postgresql' })).toBe(generated);
  });

  it.each([
    ['GENERATED', 'price INT, total INT GENERATED ALWAYS AS (price * 2) STORED'],
    ['CHECK', 'age INT CHECK (age >= 0)'],
    ['CHECK', 'age INT, CONSTRAINT chk_age CHECK (age >= 0)'],
    ['CHARACTER SET', 'name VARCHAR(20) CHARACTER SET utf8mb4'],
    ['COLLATE', 'name VARCHAR(20) COLLATE utf8mb4_bin'],
    ['ZEROFILL', 'code INT(8) ZEROFILL'],
    ['FULLTEXT', 'note TEXT, FULLTEXT INDEX ft_note (note)'],
    ['SPATIAL', 'area GEOMETRY NOT NULL, SPATIAL KEY sp_area (area)'],
    ['15 位有效数字', 'rate DECIMAL(30,20) DEFAULT 0.12345678901234567890'],
  ])('批量导入将无法保留的 %s 定义报告为失败', async (feature, definition) => {
    const unsupportedSql = `CREATE TABLE unsupported_table (${definition});`;

    const { results, failed } = await new SqlParser().parseMultiAsync(
      `CREATE TABLE supported_table (id INT); ${unsupportedSql}`,
      'mysql',
    );

    expect(results.map((result) => result.tableName)).toEqual(['supported_table']);
    expect(failed).toEqual([
      { statement: unsupportedSql, error: expect.stringContaining(feature) },
    ]);
  });

  it.each([false, true])('CREATE FULLTEXT INDEX 报告为失败（strict: %s）', async (strict) => {
    const indexSql = 'CREATE FULLTEXT INDEX ft_note ON notes (note);';

    const { results, failed } = await new SqlParser().parseMultiAsync(
      `CREATE TABLE notes (id INT, note TEXT); ${indexSql}`,
      'mysql',
      strict,
    );

    expect(results[0].indexes).toEqual([]);
    expect(failed).toEqual([{ statement: indexSql, error: expect.stringContaining('FULLTEXT') }]);
  });

  it.each([false, true])('UNIQUE INDEX 与 UNIQUE 约束同样导入（strict: %s）', async (strict) => {
    const sql = `CREATE TABLE t (
      a INT, b INT, c INT, d INT,
      UNIQUE INDEX u_a (a DESC),
      CONSTRAINT u_b UNIQUE INDEX ix_b (b),
      UNIQUE KEY u_c (c),
      CONSTRAINT u_d UNIQUE (d)
    );`;

    const { results, failed } = await new SqlParser().parseMultiAsync(sql, 'mysql', strict);

    expect(failed).toEqual([]);
    expect(results[0].indexes.map(({ name, fields, kind }) => ({ name, fields, kind }))).toEqual([
      { name: 'u_a', fields: [{ name: 'a', direction: 'DESC' }], kind: 'unique_constraint' },
      { name: 'u_b', fields: [{ name: 'b', direction: 'ASC' }], kind: 'unique_constraint' },
      { name: 'u_c', fields: [{ name: 'c', direction: 'ASC' }], kind: 'unique_constraint' },
      { name: 'u_d', fields: [{ name: 'd', direction: 'ASC' }], kind: 'unique_constraint' },
    ]);
  });
});
